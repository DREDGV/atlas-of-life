import assert from 'node:assert/strict';
import { state } from '../js/state.js';
import { captureInbox, updateInbox, routeInboxToKnowledge, revertInboxRoute, applyRemoteInboxUpdate, deleteInbox, deleteDomain } from '../js/core/commands.js';
import { saveState, loadState, importJsonV26 } from '../js/storage.js';
import adapter from '../js/storageAdapter.js';
import { listOutbox } from '../js/sync/outbox.js';

const memory = new Map();
globalThis.localStorage = { getItem: k => memory.get(k) ?? null, setItem: (k,v) => memory.set(k,String(v)), removeItem: k => memory.delete(k) };
state.domains = [{ id:'d1', title:'Дом' }, { id:'d2', title:'Дача' }];
state.projects = [{ id:'p1', domainId:'d1', title:'Ремонт' }];
for (const kind of ['thought', 'note']) {
  const [item] = captureInbox('Исходник\nВторая строка', { splitLines:false, itemType:kind });
  updateInbox(item.id, { text:'Отредактированный материал\nПодробности' });
  assert.throws(() => routeInboxToKnowledge(item.id, { domainId:'missing' }));
  assert.throws(() => routeInboxToKnowledge(item.id, { projectId:'missing' }));
  const { material } = routeInboxToKnowledge(item.id, kind === 'thought' ? { projectId:'p1' } : {});
  assert.equal(item.rawText, 'Исходник\nВторая строка');
  assert.equal(material.text, 'Отредактированный материал\nПодробности');
  assert.equal(material.sourceInboxId, item.id);
  assert.equal(item.resultRef.id, material.id);
  assert.equal(material.kind, kind);
  assert.equal(material.projectId, kind === 'thought' ? 'p1' : null);
  assert.equal(state.tasks.length, 0);
  assert.throws(() => routeInboxToKnowledge(item.id));
  assert.throws(() => updateInbox(item.id, { status:'reviewed' }));
  assert.throws(() => deleteInbox(item.id));
  if (kind === 'thought') assert.throws(() => deleteDomain('d1', { mode:'cascade' }));
  assert.equal(listOutbox().at(-1).operation.type, 'inbox.update');
  assert.equal(listOutbox().at(-1).operation.payload.after.resultRef.type, 'knowledge');
  const receipt = structuredClone(item);
  assert.throws(() => applyRemoteInboxUpdate(item.id, { ...receipt, status:'reviewed', resultRef:null }));
  material.updatedAt++;
  assert.equal(revertInboxRoute(item.id).refused, true);
  material.updatedAt = material.createdAt;
  saveState();
  state.knowledge = [];
  assert.equal(loadState(), true);
  assert.equal(state.knowledge[0].text, material.text);
  revertInboxRoute(item.id);
  assert.equal(state.knowledge.length, 0);
  const local = state.inbox.find(entry => entry.id === item.id);
  assert.equal(local.status, 'reviewed');
  // Another updated client can display the receipt, but cannot delete the owner material.
  applyRemoteInboxUpdate(item.id, receipt);
  assert.equal(revertInboxRoute(item.id).reason, 'knowledge-remote');
  applyRemoteInboxUpdate(item.id, { ...receipt, status:'reviewed', resultRef:null });
  assert.equal(local.resultRef, undefined);
}
const [item] = captureInbox('Rollback', { itemType:'note' });
const before = JSON.stringify(state);
const save = adapter.save;
adapter.save = () => { throw new Error('disk full'); };
const warn = console.warn;
console.warn = () => {};
assert.throws(() => routeInboxToKnowledge(item.id), /disk full/);
console.warn = warn;
adapter.save = save;
assert.equal(JSON.stringify(state), before);
routeInboxToKnowledge(item.id);
const routedState = JSON.stringify(state);
adapter.save = () => { throw new Error('disk full'); };
console.warn = () => {};
assert.throws(() => revertInboxRoute(item.id), /disk full/);
console.warn = warn;
adapter.save = save;
assert.equal(JSON.stringify(state), routedState);
const exported = adapter.load();
globalThis.FileReader = class {
  readAsText(text){ this.result = text; this.onload(); }
};
state.knowledge = [];
await importJsonV26(exported);
assert.equal(state.knowledge.length, 1);
assert.equal(state.inbox.find(entry => entry.id === item.id).resultRef.id, state.knowledge[0].id);
adapter.save(JSON.stringify({ schema:5, domains:[], projects:[], tasks:[], inbox:[{ id:'legacy', text:'Old note', rawText:'Original', itemType:'note', status:'processed' }] }));
loadState();
assert.deepEqual(state.knowledge, []);
assert.equal(state.inbox[0].resultRef, undefined);
assert.equal(JSON.parse(adapter.load()).schema, 6);
assert.deepEqual(JSON.parse(adapter.load()).knowledge, []);
console.log('Knowledge Foundation: routing, context, rawText, links, locks, revert, storage/import/migration, receipt and route/revert rollback passed.');
