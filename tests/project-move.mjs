import assert from 'node:assert/strict';
import { state } from '../js/state.js';
import adapter from '../js/storageAdapter.js';
import { loadState } from '../js/storage.js';
import { createDomain, createProject, captureInbox, routeInboxToTask, routeInboxToKnowledge, moveProject, undoProjectMove, updateProject } from '../js/core/commands.js';
import { listOutbox } from '../js/sync/outbox.js';
import { knowledgeContext } from '../js/features/knowledge/model.js';
const memory = new Map();
globalThis.localStorage = { getItem: k => memory.get(k) ?? null, setItem: (k,v) => memory.set(k,String(v)), removeItem: k => memory.delete(k) };
const a = createDomain({ title: 'Дом' });
const b = createDomain({ title: 'Работа' });
const p = createProject({ title: 'Проект', domainId: a.id });
const [source] = captureInbox('Неизменный оригинал', { itemType: 'task' });
const { task } = routeInboxToTask(source.id, { projectId: p.id });
const [note] = captureInbox('Материал проекта', { itemType: 'note' });
const { material } = routeInboxToKnowledge(note.id, { projectId: p.id });
const originalTask = JSON.stringify(task), originalMaterial = JSON.stringify(material), raw = source.rawText;
const before = JSON.stringify(state);
assert.throws(() => moveProject(p.id, 'missing'));
assert.equal(JSON.stringify(state), before);
const save = adapter.save, warn = console.warn;
adapter.save = () => { throw new Error('disk full'); }; console.warn = () => {};
const outboxBefore = JSON.stringify(listOutbox());
assert.throws(() => moveProject(p.id, b.id), /disk full/);
assert.equal(JSON.stringify(state), before); assert.equal(JSON.stringify(listOutbox()), outboxBefore);
adapter.save = save; console.warn = warn;
const moved = moveProject(p.id, b.id);
assert.equal(moved.operation.type, 'project.move');
assert.equal(JSON.stringify(state.tasks.find(t => t.id === task.id)), originalTask);
assert.equal(JSON.stringify(state.knowledge.find(k => k.id === material.id)), originalMaterial);
assert.equal(state.inbox.find(i => i.id === source.id).rawText, raw);
assert.equal(knowledgeContext(state, material).domain.id, b.id);
const projected = listOutbox().filter(e => e.operation.type === 'task.result.upsert').at(-1).operation.payload.projection;
assert.equal(projected.domainId, b.id); assert.equal(projected.domainTitle, 'Работа');
loadState(); assert.equal(state.projects.find(x => x.id === p.id).domainId, b.id);
const undone = undoProjectMove(moved);
assert.equal(undone.project.domainId, a.id); assert.equal(undone.operation.type, 'project.move.undo');
const again = moveProject(p.id, b.id);
updateProject(p.id, { title: 'Changed' });
assert.throws(() => undoProjectMove(again), /изменился/);
assert.equal(state.projects.find(x => x.id === p.id).domainId, b.id);
console.log('PASS project move: atomic save, rollback/outbox, stable links/rawText, material context, C2, reload, guarded undo');
