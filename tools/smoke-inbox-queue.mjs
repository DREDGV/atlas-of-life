import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
import { startStaticServer, closeAll } from './smoke-shared.mjs';

const server = await startStaticServer();
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1100, height: 800 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(8000);
const button = name => page.getByRole('button', { name, exact: true });
const tab = name => page.locator(`[data-queue-filter="${name}"]`);
const search = page.getByRole('searchbox', { name: 'Найти во входящих' });
const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('atlas_v2_data')));
const texts = ['Замерить створку', 'Купить жёлтые винты', 'Сохранить схему люка', 'Подумать об уплотнителе'];

try {
  await page.goto(server.origin);
  const { id: projectId } = await page.evaluate(async () => {
    const { createDomain, createProject } = await import('/js/core/commands.js');
    const sphere = createDomain({ title: 'Мастерская' });
    return createProject({ title: 'Люк', domainId: sphere.id });
  });
  await page.locator('#btnInbox').click();
  await page.locator('.inbox-button--capture').click();
  await page.locator('#inboxCaptureText').fill(texts.join('\n'));
  await page.locator('#inboxCaptureSave').click();
  await button('Разобрать сейчас').click();
  assert.equal(await page.locator('.inbox-list .inbox-row').count(), 4);
  assert.equal(await search.isVisible(), false);
  await page.locator('.inbox-queue-tools summary').click();
  await search.fill('ЖЁЛТЫЕ');
  assert.equal(await page.locator('.inbox-list .inbox-row').count(), 1);
  assert.match(await page.locator('.inbox-list').innerText(), /Купить жёлтые винты/);
  await search.fill('Отсутствующая запись');
  assert.match(await page.locator('.inbox-empty-block').innerText(), /Ничего не найдено/);
  await search.fill('');

  await button('Выбрать несколько').click();
  await page.getByRole('checkbox', { name: texts[0] }).check();
  await search.fill('ЖЁЛТЫЕ');
  assert.match(await page.locator('.inbox-batch-bar').innerText(), /Выбрано: 0/);
  await search.fill('');
  await page.getByRole('checkbox', { name: texts[0] }).check();
  await page.getByRole('checkbox', { name: texts[1] }).check();
  await page.locator('[data-batch-type=task]').click();
  const beforePlacement = (await saved()).operationLog.length;
  await page.getByLabel('Сфера для выбранных задач').selectOption({ label: 'Мастерская' });
  await page.getByLabel('Проект для выбранных задач').selectOption({ label: 'Люк' });
  assert.equal((await saved()).operationLog.length, beforePlacement);
  mkdirSync('output/map-day', { recursive: true });
  await page.screenshot({ path: 'output/map-day/inbox-batch.png' });
  await button('Создать 2 задачи').click();
  const batch = await saved();
  assert.equal(batch.tasks.length, 2);
  assert.ok(batch.tasks.every(task => task.projectId === projectId && batch.inbox.find(item => item.id === task.sourceInboxId)?.resultRef?.id === task.id));
  assert.equal(batch.inbox.filter(item => item.status === 'processed').length, 2);
  assert.equal(await page.locator('#inboxCount').innerText(), '2');

  await search.fill('Схему люка');
  await page.locator('[data-item-type=task]').click();
  await page.locator('summary').getByText('Уточнить название задачи', { exact: true }).click();
  await page.getByLabel('Название задачи', { exact: true }).fill('Проверить чертёж');
  await button('Создать задачу').click();
  await button('Открыть задачу').waitFor();
  await page.reload();
  await page.locator('#btnInbox').click();
  await tab('done').click();
  await page.locator('.inbox-queue-tools summary').click();
  await search.fill('Проверить чертёж');
  assert.equal(await page.locator('.inbox-list .inbox-row').count(), 1);
  assert.match(await page.locator('.inbox-result').innerText(), /Проверить чертёж/);
  await page.locator('.inbox-record-tools summary').click();
  await page.getByRole('button', { name: /Исходник/ }).click();
  assert.match(await page.locator('.inbox-provenance').innerText(), /Сохранить схему люка/);
  await search.fill('Купить жёлтые винты');
  await button('Вернуть в разбор').click();
  const afterRevert = await saved();
  const reverted = afterRevert.inbox.find(item => item.rawText === texts[1]);
  assert.equal(reverted.status, 'reviewed');
  assert.ok(!reverted.resultRef);
  assert.ok(!afterRevert.tasks.some(task => task.sourceInboxId === reverted.id));
  await tab('review').click();
  await button('Создать задачу').waitFor();
  await page.locator('.inbox-button--capture').click();
  await page.locator('#inboxCaptureText').fill('Заказать прокладку');
  await page.locator('#inboxCaptureRefine').click();
  await page.locator('[data-capture-hint=task]').click();
  await page.locator('.inbox-capture-hints-block select').selectOption({ label: 'Мастерская' });
  await page.locator('#inboxCaptureSave').click();
  await button('Разобрать сейчас').click();
  assert.match(await page.locator('.inbox-type-help').innerText(), /Подсказка из захвата · Задача/);
  await page.locator('[data-item-type=task]').click();
  const sphere = page.getByLabel('Сфера назначения', { exact: true });
  assert.equal(await sphere.inputValue(), '');
  await button('Из захвата · Мастерская').click();
  assert.ok(await sphere.inputValue());
  await sphere.selectOption('');
  await button('Создать задачу').click();
  assert.equal((await saved()).tasks.find(task => task.title === 'Заказать прокладку').domainId, null);
  assert.deepEqual(errors, []);
  console.log('PASS inbox queue: search, empty results, selection boundaries, batch routing, archive after reload, original source and safe revert');
} finally {
  await browser.close();
  await closeAll(server);
}
