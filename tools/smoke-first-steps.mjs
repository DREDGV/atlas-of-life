import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
import { startStaticServer, closeAll } from './smoke-shared.mjs';

const server = await startStaticServer();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(8000);
const button = name => page.getByRole('button', { name, exact: true });
const title = 'Купить батарейки для фонаря';
const hatch = 'Сделать и напечатать 3D-модели шарниров для скрытого люка';
const firstAction = 'Снять размеры крепления';
const note = 'Размеры люка 320 × 460 мм, крепление М4';
const thought = 'Попробовать шарнир со съёмной осью';
const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('atlas_v2_data')));
const destination = page.locator('.inbox-route-destination');
const capture = async (text, type) => {
  await page.locator('#btnInbox').click();
  await page.locator('.inbox-button--capture').click();
  await page.locator('#inboxCaptureText').fill(text);
  await page.locator('#inboxCaptureSave').click();
  await button('Разобрать сейчас').click();
  await page.locator(`[data-item-type="${type}"]`).click();
};
try {
  await page.goto(server.origin);
  await button('Записать первое дело').waitFor();
  mkdirSync('output/map-day', { recursive: true });
  await page.screenshot({ path: 'output/map-day/first-steps.png' });
  await button('Записать первое дело').click();
  await page.locator('#inboxCaptureText').fill(title);
  await page.locator('#inboxCaptureSave').click();
  await button('Разобрать сейчас').waitFor();
  await page.reload();
  await button('Разобрать запись').click();
  assert.match(await page.locator('.inbox-type-help').innerText(), /сохранить справку/);
  await page.screenshot({ path: 'output/map-day/inbox-first-choice.png' });
  await page.locator('[data-item-type=task]').click();
  assert.match(await destination.innerText(), /Карта → Без сферы/);
  await button('Создать задачу').click();
  await button('Открыть задачу').click();
  assert.match(await page.locator('#inspector').innerText(), /Купить батарейки для фонаря/);
  await page.locator('#atlasNavigator [data-action=today]').click();
  await page.locator('#atlasNavigator [data-action=open-today]').click();
  await page.locator('#viewToday .todo').getByRole('button', { name: 'Выполнено', exact: true }).click();
  await page.reload();
  await page.locator('.chip[data-view=map]').click();
  await page.locator('#mapReviewEntry button').click();
  assert.match(await page.locator('.review-events').innerText(), /Задача выполнена\s+Купить батарейки для фонаря/);
  await button('Закрыть').click();
  const data = await saved();
  assert.equal(data.tasks.length, 1);
  assert.equal(data.inbox[0].rawText, title);
  assert.equal(data.inbox[0].resultRef.id, data.tasks[0].id);
  assert.equal(data.tasks[0].domainId, null);
  assert.equal(data.tasks[0].due, null);
  assert.equal(data.domains.length, 0);
  await page.locator('#mapUnassigned summary').click();
  await page.locator('#mapUnassigned button').click();
  assert.match(await page.locator('#inspector').innerText(), /Купить батарейки для фонаря/);

  await capture(hatch, 'task');
  await page.locator('.inbox-route summary').getByText('Уточнить название задачи', { exact: true }).click();
  await page.getByLabel('Название задачи', { exact: true }).fill(firstAction);
  await page.locator('.inbox-create-place summary').getByText('+ Создать сферу', { exact: true }).click();
  await page.getByLabel('Название сферы', { exact: true }).fill('Дом и ремонт');
  await button('Создать сферу').click();
  await page.locator('.inbox-create-place summary').getByText('+ Создать проект', { exact: true }).click();
  await page.getByLabel('Название проекта', { exact: true }).fill('Скрытый люк');
  await button('Создать проект').click();
  assert.match(await destination.innerText(), /Дом и ремонт → Скрытый люк/);
  assert.equal(await page.getByLabel('Название задачи', { exact: true }).inputValue(), firstAction);
  await page.screenshot({ path: 'output/map-day/inbox-hatch.png' });
  await button('Создать задачу').click();
  await button('Открыть задачу').click();
  await button('Сделать следующим шагом').click();
  assert.match(await page.locator('#mapDay').innerText(), /Снять размеры крепления[\s\S]*Следующий шаг проекта/);

  await capture(note, 'note');
  assert.match(await destination.innerText(), /Без контекста/);
  await button('Прошлое назначение · Дом и ремонт → Скрытый люк').click();
  await button('Сохранить как заметку').click();
  await button('Открыть результат').click();
  assert.match(await page.locator('#inspector').innerText(), /Размеры люка/);

  await capture(thought, 'thought');
  await button('Прошлое назначение · Дом и ремонт → Скрытый люк').click();
  await button('Сохранить как мысль').click();
  await button('Открыть результат').click();
  await button('+ Создать задачу').click();
  await page.getByLabel('Что сделать по материалу').fill('Проверить съёмную ось');
  await button('Создать связанную задачу').click();
  await page.reload();
  await page.locator('#mapDay .map-day-name').filter({ hasText: firstAction }).click();
  await page.locator('#atlasNavigator [data-action=project]').click();
  await page.locator('#inspector [data-knowledge-id]').filter({ hasText: note }).click();
  assert.match(await page.locator('#inspector').innerText(), /Скрытый люк/);
  const after = await saved();
  const step = after.tasks.find(task => task.title === firstAction);
  const project = after.projects.find(project => project.id === step.projectId);
  assert.equal(project.nextActionId, step.id);
  assert.equal(after.inbox.find(item => item.id === step.sourceInboxId).rawText, hatch);
  const linkedTask = after.tasks.find(task => task.title === 'Проверить съёмную ось');
  assert.equal(linkedTask.projectId, project.id);
  assert.equal(after.knowledge.find(item => item.id === linkedTask.sourceKnowledgeId).text, thought);
  assert.equal(after.knowledge.find(item => item.text === note).projectId, project.id);
  await page.setViewportSize({ width: 390, height: 750 });
  await capture('Купить крепёж для люка', 'task');
  await page.locator('.inbox-queue-tools summary').click();
  await page.getByRole('searchbox', { name: 'Найти во входящих' }).fill('Крепёж');
  await page.getByRole('searchbox', { name: 'Найти во входящих' }).fill('');
  await page.locator('.inbox-queue-tools summary').click();
  await page.locator('.inbox-record-tools summary').click();
  await page.getByRole('button', { name: /Исходник/ }).click();
  assert.match(await page.locator('.inbox-provenance').innerText(), /Купить крепёж для люка/);
  await page.locator('.inbox-record-tools summary').click();
  assert.ok(await page.locator('.inbox-dialog').evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.screenshot({ path: 'output/map-day/inbox-narrow.png' });
  await button('Создать задачу').click();
  await button('Открыть задачу').click();
  const fastTask = (await saved()).tasks.find(task => task.title === 'Купить крепёж для люка');
  assert.equal(fastTask.domainId, null);
  await page.locator('#taskPlace summary').click();
  await page.locator('#taskPlaceDomain').selectOption({ label: 'Дом и ремонт' });
  await page.locator('#taskPlaceProject').selectOption({ label: 'Скрытый люк' });
  await button('Сохранить место').click();
  assert.equal((await saved()).tasks.find(task => task.id === fastTask.id).projectId, project.id);
  await page.setViewportSize({ width: 1280, height: 800 });
  const snapshot = await page.evaluate(() => localStorage.getItem('atlas_v2_data'));
  await page.locator('.header-popover-secondary summary').click();
  await button('Первые шаги').click();
  await page.locator('#firstSteps[open]').waitFor();
  await button('Записать дело').click();
  await page.locator('#inboxCaptureText').waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem('atlas_v2_data')), snapshot);
  assert.deepEqual(errors, []);
  console.log('PASS first steps: shopping without sphere, hatch project and next step, note, idea and linked task, reload and help');
} catch (error) {
  await page.screenshot({ path: 'output/map-day/first-steps-error.png' });
  throw error;
} finally {
  await browser.close();
  await closeAll(server);
}
