import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
import { startStaticServer, closeAll } from './smoke-shared.mjs';
const server=await startStaticServer();const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));mkdirSync('output/project-review',{recursive:true});
try{
 await page.goto(server.origin);
 const ids=await page.evaluate(async()=>{const c=await import('/js/core/commands.js');const d=c.createDomain({title:'Творчество',color:'#f59e0b'});const p=c.createProject({title:'Портретная серия',domainId:d.id});const t=c.createTask({title:'Снять первый портрет',projectId:p.id,due:{date:'2020-01-01'}});const m=await import('/js/view_map.js');m.layoutMap();m.fitAll();return {p:p.id,t:t.id};});
 const open=async()=>page.evaluate(async id=>{const {state}=await import('/js/state.js');(await import('/js/inspector.js')).openInspectorFor({...state.projects.find(p=>p.id===id),_type:'project'});},ids.p);
 const point=await page.evaluate(async id=>{const s=(await import('/js/view_map.js')).getLayoutSnapshot();const n=s.nodes.find(n=>n.id===id);const r=document.getElementById('canvas').getBoundingClientRect();return {x:r.x+(n.x*s.scale+s.tx)/s.size.dpr,y:r.y+(n.y*s.scale+s.ty)/s.size.dpr};},ids.p);
 await page.mouse.click(point.x,point.y);
 await page.locator('[name=outcome]').waitFor();
 await page.locator('[name=outcome]').fill('Собрать серию из пяти выразительных портретов');
 await page.locator('[name=nextActionId]').selectOption(ids.t);
 await page.locator('[name=lifecycle]').selectOption('paused');
 await page.locator('[name=pauseReason]').fill('Жду свободного времени модели');
 await page.locator('[name=reviewOn]').fill('2020-01-02');
 await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 assert.match(await page.locator('.project-review-status').innerText(),/сохранено/);
 await page.screenshot({path:'output/project-review/paused-dark.png'});
 await page.reload();await open();assert.equal(await page.locator('[name=lifecycle]').inputValue(),'paused');
 assert.equal(await page.locator('[name=outcome]').inputValue(),'Собрать серию из пяти выразительных портретов');
 await page.locator('.project-review summary').click();
 assert.match(await page.locator('.project-review').innerText(),/Пора пересмотреть паузу/);
 // Genuine storage error: draft remains and no success/memory mutation occurs.
 await page.locator('[name=outcome]').fill('Черновик при ошибке');
 await page.evaluate(async()=>{const a=(await import('/js/storageAdapter.js')).default;window.originalSave=a.save;a.save=()=>{throw Error('Тест: хранилище недоступно');};});
 await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 assert.match(await page.locator('.project-review-status').innerText(),/недоступно/);
 assert.equal(await page.locator('[name=outcome]').inputValue(),'Черновик при ошибке');
 await page.evaluate(async()=>{(await import('/js/storageAdapter.js')).default.save=window.originalSave;});
 await page.getByRole('button',{name:'Сбросить черновик',exact:true}).click();
 await page.locator('[name=lifecycle]').selectOption('active');await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 await page.locator('[name=lifecycle]').selectOption('completed');await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 assert.match(await page.locator('.project-review-status').innerText(),/открытые задачи/);
 await page.getByRole('button',{name:'Сбросить черновик',exact:true}).click();
 await page.evaluate(async id=>{(await import('/js/core/commands.js')).updateTask(id,{status:'done'});},ids.t);await open();
 assert.equal(await page.locator('[name=nextActionId]').inputValue(),'');
 await page.locator('[name=lifecycle]').selectOption('completed');await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 await page.reload();await open();assert.equal(await page.locator('[name=lifecycle]').inputValue(),'completed');
 await page.locator('#atlasNavigator [data-action=expand]').click();
 assert.ok(await page.evaluate(async id=>(await import('/js/view_map.js')).getLayoutSnapshot().nodes.some(n=>n.id===id),ids.t));
 await page.locator('#atlasNavigator [data-action=expand]').click();
 await page.evaluate(async()=>{document.documentElement.dataset.theme='light';(await import('/js/view_map.js')).drawMap();});
 await page.screenshot({path:'output/project-review/completed-light.png'});
 await page.setViewportSize({width:1024,height:768});await page.screenshot({path:'output/project-review/compact.png'});
 assert.deepEqual(errors,[]);console.log('PASS browser: project decision, signals, reload, pause/resume/complete, next step cleanup, storage failure + draft, light/dark/compact');
}finally{await browser.close();await closeAll(server);}
